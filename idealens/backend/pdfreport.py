"""Dependency-free PDF export (text report, A4, Helvetica). Non-Latin characters are replaced with '?'."""
import re, textwrap

W, H, MARGIN = 595, 842, 50


def _esc(s):
    s = s.encode("latin-1", "replace").decode("latin-1")
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def build_pdf(blocks):
    """blocks: list of (style, text) with style in h1, h2, p, b (bullet)."""
    spec = {"h1": ("F2", 18, 24, 60), "h2": ("F2", 13, 18, 80), "p": ("F1", 10, 14, 94), "b": ("F1", 10, 14, 90)}
    pages, cur, y = [], [], H - MARGIN
    for style, text in blocks:
        font, size, lead, width = spec[style]
        lines = textwrap.wrap(("- " if style == "b" else "") + text, width) or [""]
        if style in ("h1", "h2"):
            y -= 6
        for i, ln in enumerate(lines):
            if y < MARGIN + 20:
                pages.append(cur); cur, y = [], H - MARGIN
            x = MARGIN + (12 if style == "b" and i > 0 else 0)
            cur.append(f"BT /{font} {size} Tf 1 0 0 1 {x} {y} Tm ({_esc(ln)}) Tj ET")
            y -= lead
    pages.append(cur)
    objs = [b"<< /Type /Catalog /Pages 2 0 R >>", None,
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"]
    kids = []
    for i, ops in enumerate(pages):
        pg, ct = 5 + 2 * i, 6 + 2 * i
        kids.append(f"{pg} 0 R")
        objs.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {W} {H}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {ct} 0 R >>".encode())
        stream = "\n".join(ops).encode("latin-1", "replace")
        objs.append(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream")
    objs[1] = f"<< /Type /Pages /Kids [{' '.join(kids)}] /Count {len(pages)} >>".encode()
    out, offs = bytearray(b"%PDF-1.4\n"), []
    for n, body in enumerate(objs, 1):
        offs.append(len(out))
        out += f"{n} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for o in offs:
        out += f"{o:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF".encode()
    return bytes(out)


def report_blocks(doc):
    r, s = doc["report"], doc["report"]["scores"]
    b = [("h1", doc["title"]), ("p", f"Status: {doc.get('status', 'draft')}   |   Version: {doc.get('version', 1)}   |   Created: {str(doc.get('created_at', ''))[:10]}"),
         ("p", doc["description"]), ("h2", f"Overall score: {s['overall']}/100 - {r['verdict']}"), ("p", r["summary"]),
         ("h2", "Scores and reasons")]
    for k in ("originality", "innovation", "feasibility", "impact", "relevance"):
        b.append(("b", f"{k.capitalize()}: {s[k]}/100 - {(r.get('reasons') or {}).get(k, '')}"))
    b.append(("p", f"Scoring mode: {r.get('scoring_mode', 'rules')}"))
    if r.get("sdgs"):
        b += [("h2", "UN Sustainable Development Goals")] + [("b", f"SDG {g['number']}: {g['name']}") for g in r["sdgs"]]
    b.append(("h2", "Similar existing projects"))
    b += [("b", f"{x['title']} ({x['similarity']}% match) - {x['domain']}") for x in r["similar"]] or [("p", "No close matches found.")]
    b.append(("h2", "Risks"))
    b += [("b", f"{k['category']} [{k['level']}]: {k['risk']} Mitigation: {k['mitigation']}") for k in r["risks"]]
    b.append(("h2", "How to improve"))
    b += [("b", x) for x in r["suggestions"]]
    t = r["technology"]
    b += [("h2", "Technology recommendation")] + [("b", f"{k}: {t[k]}") for k in ("Frontend", "Backend", "Database", "AI / ML", "Deployment")]
    if t["Extras"]:
        b.append(("b", "Also consider: " + ", ".join(t["Extras"])))
    b.append(("p", f"Estimated cost: {r['cost']['estimate']}   |   Estimated time: about {r['time_weeks']} weeks"))
    b.append(("h2", "Roadmap"))
    for p in r["roadmap"]:
        b.append(("b", f"{p['phase']} (weeks {p['from_week']}-{p['to_week']}): " + "; ".join(p["tasks"])))
    if doc.get("reviews"):
        b.append(("h2", "Reviewer feedback"))
        for v in doc["reviews"]:
            g = f" Grade {v['grade']}/10." if v.get("grade") is not None else ""
            b.append(("b", f"{v['teacher_name']} ({v['status'].replace('_', ' ')}):{g} {v['comment']}"))
    b.append(("p", "Generated by IdeaLens. Scores are guidance, not a guarantee."))
    return b
